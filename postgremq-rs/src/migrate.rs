//! Schema migrations, compatible with the Go and TypeScript clients and the
//! CLI, which all follow golang-migrate's protocol: the same version table,
//! advisory lock and dirty-flag protocol, so any client can migrate a
//! database another one installed.
//!
//! A schema version is an mq version stored as one number,
//! `major * 10^8 + minor * 10^4 + patch` (see [`format_schema_version`]).

use sqlx::{AssertSqlSafe, Connection as _, PgConnection, PgPool};
use tracing::Instrument as _;

use sqlx::postgres::{PgDatabaseError, PgErrorPosition};

use crate::error::{Error, Result, SqlPosition};

/// An embedded up migration.
struct Migration {
    version: u64,
    sql: &'static str,
}

// MIGRATIONS: every migration in migrations/, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/migrations.rs"));

/// The latest embedded migration.
const LATEST_VERSION: u64 = MIGRATIONS[MIGRATIONS.len() - 1].version;

/// The mq version (`major.minor.patch`) of a schema version: the number
/// the version table stores and [`MigrationStatus`] reports, which is
/// `major * 10^8 + minor * 10^4 + patch`.
///
/// ```
/// assert_eq!(postgremq::format_schema_version(10_000), "0.1.0");
/// assert_eq!(postgremq::format_schema_version(100_020_003), "1.2.3");
/// ```
#[must_use]
pub fn format_schema_version(version: u64) -> String {
    format!(
        "{}.{}.{}",
        version / 100_000_000,
        version / 10_000 % 10_000,
        version % 10_000
    )
}

/// golang-migrate's salt for advisory lock keys.
const LOCK_SALT: u32 = 1_486_364_155;

/// The migration state of a database, from [`migration_status`].
///
/// Not constructible outside the crate (fields may be added):
///
/// ```compile_fail,E0639
/// let _ = postgremq::MigrationStatus { ..unimplemented!() };
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub struct MigrationStatus {
    /// The applied schema version; `0` when no migration has been applied.
    /// [`format_schema_version`] gives its mq version.
    pub current_version: u64,
    /// Whether the migration of `current_version` has not finished: it
    /// failed partway, or another process is applying it right now (the
    /// status is read without the migration lock).
    pub dirty: bool,
    /// The schema version of the latest migration embedded in this crate.
    pub latest_version: u64,
    /// Whether `current_version` is below `latest_version`. A dirty database
    /// may report `false`; [`migrate`] refuses it either way. It is also
    /// `true` for a version below the latest that none of the migrations
    /// knows, which [`migrate`] refuses.
    pub needs_migration: bool,
}

/// Applies the embedded migrations the database has not applied yet, up to
/// the latest embedded version.
///
/// A database already at a newer version (migrated by a newer client) is
/// left unchanged. Concurrent callers, in any client, are serialised by an
/// advisory lock. This is schema management, separate from
/// [`Connection`](crate::Connection): run it once before connecting, e.g. at
/// application start-up.
///
/// # Cancellation
///
/// Waiting for the lock (which has no time limit) can be cancelled: dropping
/// the future ends that session. Once migrations start applying, they run to
/// completion in a spawned task even if the future is dropped, so a cancelled
/// call never leaves a migration half-recorded.
///
/// # Errors
///
/// [`Error::Migration`] when a migration fails (its version is left dirty,
/// and it is rolled back when the database reported the error);
/// [`Error::DirtySchema`] when a previous migration failed partway;
/// [`Error::UnknownSchemaVersion`] when the recorded version is below the
/// latest but none of the migrations; [`Error::Sqlx`] for other database
/// errors.
pub async fn migrate(pool: &PgPool) -> Result<()> {
    run(pool, MIGRATIONS).await
}

/// Reads the migration state. Read-only: it works before the schema is
/// installed and needs no `CREATE` privilege.
///
/// # Errors
///
/// [`Error::Sqlx`] for database errors.
pub async fn migration_status(pool: &PgPool) -> Result<MigrationStatus> {
    let installed: bool =
        sqlx::query_scalar("SELECT to_regclass('postgremq.postgremq_migrations') IS NOT NULL")
            .fetch_one(pool)
            .await
            .map_err(Error::Sqlx)?;
    let (current_version, dirty) = if installed {
        read_version(&mut *pool.acquire().await.map_err(Error::Sqlx)?).await?
    } else {
        (0, false)
    };
    Ok(MigrationStatus {
        current_version,
        dirty,
        latest_version: LATEST_VERSION,
        needs_migration: current_version < LATEST_VERSION,
    })
}

async fn run(pool: &PgPool, migrations: &'static [Migration]) -> Result<()> {
    // Detached: the session holds a session-level advisory lock, so it must
    // never go back to the pool. Dropping it ends the session and the lock.
    let mut conn = pool.acquire().await.map_err(Error::Sqlx)?.detach();
    let lock = match lock(&mut conn).await {
        Ok(lock) => lock,
        Err(err) => {
            finish(conn, None).await;
            return Err(err);
        }
    };
    let current = match applied_version(&mut conn, migrations).await {
        Ok(current) => current,
        Err(err) => {
            finish(conn, Some(lock)).await;
            return Err(err);
        }
    };
    let task = tokio::spawn(
        async move {
            let result = apply(&mut conn, migrations, current).await;
            finish(conn, Some(lock)).await;
            result
        }
        .in_current_span(),
    );
    match task.await {
        Ok(result) => result,
        Err(err) if err.is_panic() => std::panic::resume_unwind(err.into_panic()),
        // The runtime is shutting down.
        Err(_) => Err(Error::Sqlx(sqlx::Error::WorkerCrashed)),
    }
}

/// Takes the migration lock; returns its key. Safe to cancel.
async fn lock(conn: &mut PgConnection) -> Result<i64> {
    let database: String = sqlx::query_scalar("SELECT current_database()")
        .fetch_one(&mut *conn)
        .await
        .map_err(Error::Sqlx)?;
    let lock = i64::from(lock_id(&database));
    sqlx::query("SELECT pg_advisory_lock($1)")
        .bind(lock)
        .execute(&mut *conn)
        .await
        .map_err(Error::Sqlx)?;
    Ok(lock)
}

/// Under the lock: creates the version table if needed and returns the
/// applied version, refusing a dirty one and one `migrations` cannot upgrade.
/// Safe to cancel.
async fn applied_version(conn: &mut PgConnection, migrations: &[Migration]) -> Result<u64> {
    ensure_version_table(conn).await?;
    let (current, dirty) = read_version(conn).await?;
    if dirty {
        return Err(Error::DirtySchema { version: current });
    }
    // A version below the latest that is none of the migrations is not a
    // state they can upgrade from. A version above it was recorded by a
    // newer client: nothing to do.
    if current != 0
        && migrations
            .last()
            .is_some_and(|latest| current < latest.version)
        && !migrations.iter().any(|m| m.version == current)
    {
        return Err(Error::UnknownSchemaVersion { version: current });
    }
    Ok(current)
}

/// Applies the migrations above `current`, each under the dirty flag.
async fn apply(conn: &mut PgConnection, migrations: &[Migration], current: u64) -> Result<()> {
    if migrations.iter().all(|m| m.version <= current) {
        return Ok(());
    }
    let server_encoding: String = sqlx::query_scalar("SELECT current_setting('server_encoding')")
        .fetch_one(&mut *conn)
        .await
        .map_err(Error::Sqlx)?;
    let positions = position_unit(&server_encoding);
    for migration in migrations.iter().filter(|m| m.version > current) {
        tracing::info!(version = migration.version, "applying schema migration");
        set_version(conn, migration.version, true).await?;
        // The simple query protocol runs the whole file in one implicit
        // transaction, as the Go client does.
        sqlx::raw_sql(migration.sql)
            .execute(&mut *conn)
            .await
            .map_err(|source| migration_error(migration, source, positions))?;
        set_version(conn, migration.version, false).await?;
    }
    Ok(())
}

/// What a PostgreSQL error position counts in the UTF-8 migration text.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum PositionUnit {
    Characters,
    Bytes,
}

/// What the server counts an error position in, given `server_encoding`
/// (sqlx sets client_encoding to UTF8). It counts characters of the text
/// converted to the database's encoding; conversion keeps the characters,
/// except into EUC_JIS_2004, which combines some pairs into one (`None`: not
/// mapped). A SQL_ASCII database does not convert and counts bytes.
fn position_unit(server_encoding: &str) -> Option<PositionUnit> {
    match server_encoding {
        "SQL_ASCII" => Some(PositionUnit::Bytes),
        "EUC_JIS_2004" => None,
        _ => Some(PositionUnit::Characters),
    }
}

/// An [`Error::Migration`] for `migration`'s `source`, located in its file
/// when the server reports a position in `positions`.
fn migration_error(
    migration: &Migration,
    source: sqlx::Error,
    positions: Option<PositionUnit>,
) -> Error {
    let position = match (
        crate::error::pg_error(&source).and_then(PgDatabaseError::position),
        positions,
    ) {
        (Some(PgErrorPosition::Original(position)), Some(unit)) => {
            sql_position(migration.sql, position, unit)
                .and_then(|(line, column)| SqlPosition::new(line, column))
        }
        _ => None,
    };
    Error::Migration {
        version: migration.version,
        position,
        source,
    }
}

/// The line and column, from 1 and the column in characters, of a
/// PostgreSQL error position in `sql`. The position counts from 1 in `unit`;
/// one past the end is the end of the input.
fn sql_position(sql: &str, position: usize, unit: PositionUnit) -> Option<(usize, usize)> {
    let offset = position.checked_sub(1)?;
    let before = if unit == PositionUnit::Bytes {
        sql.get(..offset)?
    } else {
        let end = sql
            .char_indices()
            .map(|(index, _)| index)
            .chain([sql.len()])
            .nth(offset)?;
        &sql[..end]
    };
    let line_start = before.rfind('\n').map_or(0, |newline| newline + 1);
    Some((
        before.matches('\n').count() + 1,
        before[line_start..].chars().count() + 1,
    ))
}

/// Releases the lock and ends the session. Failures are only logged: ending
/// the session releases the lock anyway.
async fn finish(mut conn: PgConnection, lock: Option<i64>) {
    if let Some(lock) = lock
        && let Err(err) = sqlx::query("SELECT pg_advisory_unlock($1)")
            .bind(lock)
            .execute(&mut conn)
            .await
    {
        tracing::debug!(
            error = &err as &dyn std::error::Error,
            "migration unlock failed"
        );
    }
    if let Err(err) = conn.close().await {
        tracing::warn!(
            error = &err as &dyn std::error::Error,
            "closing the migration session failed"
        );
    }
}

/// golang-migrate's lock key for the version table: CRC-32 (IEEE) of
/// `"postgremq\0postgremq_migrations\0<database>"`, times its salt.
fn lock_id(database: &str) -> u32 {
    let key = format!("postgremq\0postgremq_migrations\0{database}");
    crc32(key.as_bytes()).wrapping_mul(LOCK_SALT)
}

fn crc32(data: &[u8]) -> u32 {
    !data.iter().fold(!0_u32, |crc, &byte| {
        (0..8).fold(crc ^ u32::from(byte), |c, _| {
            if c & 1 == 1 {
                0xedb8_8320 ^ (c >> 1)
            } else {
                c >> 1
            }
        })
    })
}

/// Creates the schema and version table if missing. Runs under the lock, and
/// checks first, so an installed database needs no `CREATE` privilege.
async fn ensure_version_table(conn: &mut PgConnection) -> Result<()> {
    let (schema_exists, table_exists): (bool, bool) = sqlx::query_as(
        "SELECT to_regnamespace('postgremq') IS NOT NULL, \
                to_regclass('postgremq.postgremq_migrations') IS NOT NULL",
    )
    .fetch_one(&mut *conn)
    .await
    .map_err(Error::Sqlx)?;
    if !schema_exists {
        sqlx::raw_sql("CREATE SCHEMA IF NOT EXISTS postgremq")
            .execute(&mut *conn)
            .await
            .map_err(Error::Sqlx)?;
    }
    if !table_exists {
        sqlx::raw_sql(
            "CREATE TABLE IF NOT EXISTS postgremq.postgremq_migrations \
             (version bigint not null primary key, dirty boolean not null)",
        )
        .execute(&mut *conn)
        .await
        .map_err(Error::Sqlx)?;
    }
    Ok(())
}

async fn read_version(conn: &mut PgConnection) -> Result<(u64, bool)> {
    let row: Option<(i64, bool)> =
        sqlx::query_as("SELECT version, dirty FROM postgremq.postgremq_migrations LIMIT 1")
            .fetch_optional(&mut *conn)
            .await
            .map_err(Error::Sqlx)?;
    let Some((version, dirty)) = row else {
        return Ok((0, false));
    };
    // golang-migrate records -1 (no version) after a failed first down
    // migration.
    Ok((u64::try_from(version).unwrap_or(0), dirty))
}

/// Replaces the version row atomically (one implicit transaction).
async fn set_version(conn: &mut PgConnection, version: u64, dirty: bool) -> Result<()> {
    sqlx::raw_sql(AssertSqlSafe(format!(
        "TRUNCATE postgremq.postgremq_migrations; \
         INSERT INTO postgremq.postgremq_migrations (version, dirty) VALUES ({version}, {dirty})"
    )))
    .execute(&mut *conn)
    .await
    .map_err(Error::Sqlx)?;
    Ok(())
}

