    #[test]
    fn embeds_every_migration_in_order() -> std::io::Result<()> {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("migrations");
        let mut files: Vec<String> = std::fs::read_dir(&dir)?
            .map(|entry| entry.map(|e| e.file_name().to_string_lossy().into_owned()))
            .collect::<std::io::Result<_>>()?;
        files.retain(|name| name.ends_with(".up.sql"));
        files.sort();
        assert_eq!(MIGRATIONS.len(), files.len());
        for (file, migration) in files.iter().zip(MIGRATIONS) {
            assert_eq!(
                file,
                &format!(
                    "{:09}_{}.up.sql",
                    migration.version,
                    format_schema_version(migration.version)
                ),
                "{file} is embedded in order"
            );
            assert_eq!(std::fs::read_to_string(dir.join(file))?, migration.sql);
        }
        Ok(())
    }

